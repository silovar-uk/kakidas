import assert from 'node:assert/strict';
import { chromium } from 'playwright';
import fs from 'node:fs';
const base=process.env.BASE_URL||'http://127.0.0.1:4173/';
const b=await chromium.launch({headless:true});
const ctx=await b.newContext({acceptDownloads:true,locale:'ja-JP'});
const page=await ctx.newPage();
let externalRequests=[];
page.on('request',r=>{if(!r.url().startsWith(base)&&!r.url().startsWith('data:'))externalRequests.push(r.url())});
await page.goto(new URL('outliner-study.html',base).href);
await page.locator('#pid').fill('TEST-01');
await page.locator('#consent').check();
await page.locator('#begin').click();
const status=await page.locator('#order').textContent();
assert.match(status,/割当：(?:AB|BA)/);
for(let i=0;i<8;i++){
  assert.equal(await page.locator('#start').isEnabled(),true,'start '+i);
  await page.locator('#start').click();
  await page.waitForTimeout(10);
  await page.locator('#stop').click();
  if(i===7)await page.locator('#success').selectOption('NA');
  await page.locator('#save').click();
}
assert.match(await page.locator('#stage').textContent(),/全課題の記録が終了/);
const download=page.waitForEvent('download');
await page.locator('#export').click();
const dl=await download;
const local=await dl.path();
const output=JSON.parse(fs.readFileSync(local,'utf8'));
assert.equal(output.schema_version,1);
assert.equal(output.participant_code,'TEST-01');
assert.equal(output.records.length,8);
const conds=output.records.map(r=>r.condition);
assert(conds.slice(0,4).every(x=>x===conds[0]));
assert(conds.slice(4).every(x=>x!==conds[0]));
assert.equal(output.records[7].success,'NA');
assert.deepEqual(externalRequests,[],'no telemetry network calls expected');
console.log('PASS study recorder: consent/order/8 tasks/JSON/no telemetry',JSON.stringify({order:output.order,count:output.records.length}));
await page.goto(new URL('outliner-lab.html?study=1',base).href);
assert.equal(await page.evaluate(()=>window.__kakidasLab.getState().nodes.length),0,'study must start with an empty tree');
await page.locator('#add-end').click();
assert.equal(await page.evaluate(()=>window.__kakidasLab.getState().nodes.length),1);
await page.reload();
assert.equal(await page.evaluate(()=>window.__kakidasLab.getState().nodes.length),1,'study data persists');
await page.goto(new URL('outliner-lab.html',base).href);
assert.equal(await page.evaluate(()=>window.__kakidasLab.getState().nodes.length),7,'normal demo stays untouched');
console.log('PASS isolated study storage and equal empty starting condition');
await b.close();